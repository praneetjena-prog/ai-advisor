@app.post("/api/generate-response")
def generate_model_response(req: GenerateResponseRequest):
    if not req.prompt.strip():
        raise HTTPException(status_code=400, detail="Prompt cannot be empty.")

    m_id = req.model.lower()
    user_key = (req.api_key or "").strip()

    # 1. LIVE GOOGLE GEMINI API
    if "gemini" in m_id:
        key = user_key or os.environ.get("GEMINI_API_KEY", "")
        if key:
            try:
                model_name = "gemini-1.5-pro" if "pro" in m_id else "gemini-1.5-flash"
                if "25" in m_id or "35" in m_id or "31" in m_id:
                    model_name = "gemini-2.5-pro" if "pro" in m_id else "gemini-2.5-flash"
                
                url = f"https://generativelanguage.googleapis.com/v1beta/models/{model_name}:generateContent?key={key}"
                contents = []
                if req.system_prompt:
                    contents.append({"role": "user", "parts": [{"text": f"System Instructions: {req.system_prompt}"}]})
                    contents.append({"role": "model", "parts": [{"text": "Understood. I will follow these system instructions."}]})
                contents.append({"role": "user", "parts": [{"text": req.prompt}]})

                payload = {
                    "contents": contents,
                    "generationConfig": {
                        "temperature": req.temperature or 0.2,
                        "maxOutputTokens": req.max_tokens or 4096
                    }
                }

                req_obj = urllib.request.Request(
                    url,
                    data=json.dumps(payload).encode('utf-8'),
                    headers={'Content-Type': 'application/json'}
                )
                with urllib.request.urlopen(req_obj, timeout=30) as resp:
                    res_data = json.loads(resp.read().decode('utf-8'))
                    text = res_data['candidates'][0]['content']['parts'][0]['text']
                    return {
                        "output": text,
                        "model": req.model,
                        "provider": "Google Gemini (Live API)",
                        "live_api": True
                    }
            except Exception:
                pass

        return {
            "output": generate_gemini_signature_response(req.model, req.prompt, req.system_prompt, req.temperature),
            "model": req.model,
            "provider": "Google (Real Model Architecture Signature)",
            "live_api": False
        }

    # 2. LIVE OPENAI / CHATGPT API
    elif "gpt" in m_id or "o3" in m_id or "openai" in m_id:
        key = user_key or os.environ.get("OPENAI_API_KEY", "")
        if key:
            try:
                model_name = "gpt-4o"
                if "o3-mini" in m_id:
                    model_name = "o3-mini"
                elif "o3" in m_id:
                    model_name = "o3"
                elif "4-1-mini" in m_id:
                    model_name = "gpt-4o-mini"
                elif "4-1" in m_id:
                    model_name = "gpt-4o"

                messages = []
                if req.system_prompt:
                    messages.append({"role": "system", "content": req.system_prompt})
                messages.append({"role": "user", "content": req.prompt})

                url = "https://api.openai.com/v1/chat/completions"
                payload = {
                    "model": model_name,
                    "messages": messages,
                    "temperature": req.temperature or 0.2,
                    "max_tokens": req.max_tokens or 4096
                }

                req_obj = urllib.request.Request(
                    url,
                    data=json.dumps(payload).encode('utf-8'),
                    headers={
                        'Content-Type': 'application/json',
                        'Authorization': f'Bearer {key}'
                    }
                )
                with urllib.request.urlopen(req_obj, timeout=30) as resp:
                    res_data = json.loads(resp.read().decode('utf-8'))
                    text = res_data['choices'][0]['message']['content']
                    return {
                        "output": text,
                        "model": req.model,
                        "provider": f"OpenAI {model_name} (Live API)",
                        "live_api": True
                    }
            except Exception:
                pass

        return {
            "output": generate_openai_signature_response(req.model, req.prompt, req.system_prompt, req.temperature),
            "model": req.model,
            "provider": "OpenAI (Real Model Architecture Signature)",
            "live_api": False
        }

    # 3. LIVE ANTHROPIC CLAUDE API
    elif "claude" in m_id:
        key = user_key or os.environ.get("ANTHROPIC_API_KEY", "")
        if key:
            try:
                model_name = "claude-3-5-sonnet-20241022"
                if "haiku" in m_id:
                    model_name = "claude-3-5-haiku-20241022"
                elif "opus" in m_id:
                    model_name = "claude-3-opus-20240229"

                url = "https://api.anthropic.com/v1/messages"
                payload = {
                    "model": model_name,
                    "max_tokens": req.max_tokens or 4096,
                    "messages": [{"role": "user", "content": req.prompt}]
                }
                if req.system_prompt:
                    payload["system"] = req.system_prompt

                req_obj = urllib.request.Request(
                    url,
                    data=json.dumps(payload).encode('utf-8'),
                    headers={
                        'Content-Type': 'application/json',
                        'x-api-key': key,
                        'anthropic-version': '2023-06-01'
                    }
                )
                with urllib.request.urlopen(req_obj, timeout=30) as resp:
                    res_data = json.loads(resp.read().decode('utf-8'))
                    text = res_data['content'][0]['text']
                    return {
                        "output": text,
                        "model": req.model,
                        "provider": f"Anthropic {model_name} (Live API)",
                        "live_api": True
                    }
            except Exception:
                pass

        return {
            "output": generate_claude_signature_response(req.model, req.prompt, req.system_prompt, req.temperature),
            "model": req.model,
            "provider": "Anthropic (Real Model Architecture Signature)",
            "live_api": False
        }

    return {
        "output": generate_generic_signature_response(req.model, req.prompt, req.system_prompt),
        "model": req.model,
        "provider": "Model Provider Architecture Signature",
        "live_api": False
    }

@app.post("/api/optimize-prompt")
def optimize_prompt(req: PromptOptimizationRequest):
    if not req.task.strip():
        raise HTTPException(status_code=400, detail="Task description cannot be empty.")
    
    role_text = f"You are an expert AI agent configured to execute: '{req.task}'."
    
    model_opt = ""
    if "gemini" in req.model:
        model_opt = "- Optimize for Gemini by structuring reasoning in explicit steps.\n- Use structured JSON outputs where appropriate to take advantage of schema parsing."
    elif "claude" in req.model:
        model_opt = "- Optimize for Claude by using XML tags for separating reasoning and final answers (e.g., <thinking> and <answer>).\n- Leverage Claude's precise tool-use formatting."
    elif "gpt" in req.model or "o3" in req.model:
        model_opt = "- Optimize for OpenAI by providing structured system instructions and explicit task boundaries.\n- Rely on JSON schema output format."
    elif "deepseek" in req.model:
        model_opt = "- Optimize for DeepSeek R1 by outputting deep reasoning thoughts inside <think>...</think> tags."

    complexity_text = ""
    if req.complexity == "simple":
        complexity_text = "- Keep operations linear and direct.\n- Fail fast and return clear error responses immediately."
    elif req.complexity == "moderate":
        complexity_text = "- Breakdown the request into 2-3 logical stages.\n- Verify outputs between stages."
    elif req.complexity == "complex":
        complexity_text = "- Maintain a robust execution state graph.\n- Implement a double-check validation loop before committing outputs.\n- Catch exceptions and run self-correction prompts automatically."

    system_prompt = f"""# SYSTEM PROMPT

## Role & Mission
{role_text}

## Execution Instructions
- Goal: Execute the task perfectly without errors.
- Output Format: Follow the rules defined in the format section.

## Model-Specific Optimizations
{model_opt}

## Complexity Constraints ({req.complexity})
{complexity_text}

## Error Prevention & Guardrails
- Validate all incoming arguments to tools before execution.
- If a tool fails, capture the stdout/stderr, analyze the error, self-correct, and retry.
- Do not loop infinitely. If a step fails 3 times, bubble up the error details with a recovery plan.

## Format Instructions
Produce a clean, concise final answer. Do not include markdown warnings or metadata notes.
"""

    config_template = f"""# CONFIGURATION TEMPLATE
model: {req.model}
temperature: 0.1
max_tokens: 4096
top_p: 0.95
safety_settings:
  block_low_confidence: true
tools:
  - name: file_editor
    description: Allows editing files locally
  - name: terminal_run
    description: Runs command line checks
retry_policy:
  max_retries: 3
  initial_delay_sec: 2
  backoff_multiplier: 2.0
"""

    if req.format == "system-prompt":
        output = system_prompt.strip()
    elif req.format == "config":
        output = config_template.strip()
    else:
        output = f"{system_prompt.strip()}\n\n---\n\n{config_template.strip()}"

    return {"output": output}

@app.get("/api/simulate/{scenario_id}")
def simulate_agent(scenario_id: str, speed: float = 1.0):
    if scenario_id not in ["coding", "research", "data-processing"]:
        raise HTTPException(status_code=404, detail="Scenario not found.")
        
    return StreamingResponse(
        agent_simulator.stream_simulation(scenario_id, speed),
        media_type="text/event-stream"
    )

